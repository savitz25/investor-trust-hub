import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { publicationMetricInputs } from './publication_metric_inputs.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (path) => readFileSync(join(root, path), 'utf8');
const registration = JSON.parse(read('data/alabama/al-inv-001/registration-lenses.json'));
const orders = JSON.parse(read('data/alabama/al-inv-001/securities-orders.json'));
const page = read('apps/web/src/app/alabama/page.tsx');
assert(publicationMetricInputs().publishedStateIntelligencePaths.includes('/alabama'));
for (const city of ['birmingham', 'montgomery', 'huntsville', 'mobile', 'tuscaloosa']) {
  assert(!existsSync(join(root, 'apps/web/src/app/alabama', city)));
}
assert(page.includes("path: '/alabama'"));
assert(page.includes('Alabama Securities Commission'));
assert(!/AggregateRating|ratingValue|Trust Score|best adviser|safest adviser/i.test(page));
assert(!page.includes('1913') && !page.includes('1,913') && !page.includes('1804'));
const lists = registration.identifierLists;
assert.equal(registration.stateFeed.sourceAsOf, '2026-09-17');
assert.equal(registration.stateFeed.sha256, '5fa17c38ae2e812dbd4d58c359c4d624a54417e3f794a3287c3414ccfdaa6a02');
assert.equal(registration.secFeed.sha256, 'f01d6b17a7ed631125e76d3c1e5965f178235273eea6699c15400473cb2f1f22');
assert.equal(registration.stateIa.status, 'APPROVED');
assert.equal(registration.stateIa.count, lists.stateIaApprovedFirmCrds.length);
assert.equal(registration.era.count, lists.eraActiveFirmCrds.length);
assert.equal(registration.federalNotice.count, lists.noticeFiledFirmCrds.length);
assert.deepEqual([registration.stateIa.count, registration.era.count, registration.federalNotice.count, registration.principalOffice.count], [165, 21, 1639, 98]);
assert.equal(registration.principalOffice.sourceAsOf, '2026-08-27');
assert.match(registration.principalOffice.grain, /not Alabama registration/i);
assert.equal(registration.stateIa.filter.includes('MainAddr'), false);
assert.equal(registration.era.filter.includes('MainAddr'), false);
assert.equal(registration.federalNotice.filter.includes('MainAddr'), false);
for (const values of Object.values(lists)) assert.equal(new Set(values).size, values.length);
const set = (xs) => new Set(xs);
const inter = (a, b) => [...set(a)].filter((x) => set(b).has(x)).sort((x, y) => Number(x) - Number(y));
assert.deepEqual(registration.exactCrdIntersections.stateIaApprovedAndNoticeFiled, inter(lists.stateIaApprovedFirmCrds, lists.noticeFiledFirmCrds));
assert.deepEqual(registration.exactCrdIntersections.stateIaAndEra, inter(lists.stateIaApprovedFirmCrds, lists.eraActiveFirmCrds));
assert.deepEqual(registration.exactCrdIntersections.eraAndNoticeFiled, inter(lists.eraActiveFirmCrds, lists.noticeFiledFirmCrds));
assert.equal(registration.exactCrdIntersections.principalOfficeOverlay, null);
assert.equal(registration.dedupedAlabamaAdvisers, null);
assert.equal(registration.graphWrites, 0);
assert.equal(registration.newCanonicalFirms, 0);
assert.equal(registration.canonicalReconciliation.netNewCanonicalFirms, 0);
assert.equal(registration.canonicalReconciliation.existingCanonicalMatches, null);
assert.equal(registration.canonicalReconciliation.unresolvedIdentities, 165);
assert.equal(orders.status, 'BOUNDED_INDEX');
assert.equal(orders.rowCount, 33);
assert.equal(orders.rows.length, 33);
assert.equal(orders.exactEnforcementAttachments, 0);
assert.equal(orders.nameOnlyAdverseJoins, 0);
assert.equal(orders.graphWrites, 0);
assert.equal(orders.rowsWithCrdColumn, 0);
assert.equal(orders.ceaseAndDesistIsFinalAdjudication, false);
