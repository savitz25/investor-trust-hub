import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { publicationMetricInputs } from './publication_metric_inputs.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (path) => readFileSync(join(root, path), 'utf8');
const registration = JSON.parse(read('data/mississippi/ms-inv-001/registration-lenses.json'));
const orders = JSON.parse(read('data/mississippi/ms-inv-001/securities-orders.json'));
